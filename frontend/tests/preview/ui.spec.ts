import { test, expect } from '@playwright/test'

test('bestehende UI zeigt gekennzeichnete Testdaten und temporäre Bewertungen', async ({ page }, testInfo) => {
  await page.goto('/dashboard')
  await page.getByRole('button', { name: 'Testdaten zurücksetzen' }).click()
  await expect(page.getByText('Testdaten-Vorschau · simulierte Aufträge')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Betriebsübersicht' })).toBeVisible()
  await page.getByRole('navigation', { name: 'Hauptnavigation' }).getByRole('link', { name: 'Fertigungsaufträge' }).click()
  await expect(page.getByText('Testdaten-Vorschau · simulierte Aufträge')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Produktqueue dieses Laufs' })).toBeVisible()
  await page.getByRole('button', { name: 'Lauf prüfen', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('radio', { name: 'Abgeschlossen', exact: true }).click()
  await dialog.getByLabel('Erfolgreiche Einheiten').fill('2')
  await dialog.getByLabel('Fehlgeschlagene Einheiten').fill('1')
  await dialog.getByRole('button', { name: 'Bewertung speichern' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Manuell bewertet')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Lauf prüfen', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Testdaten zurücksetzen' }).click()
  await expect(page.getByRole('button', { name: 'Lauf prüfen', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('testdata-preview.png'), fullPage: true })
  await page.getByRole('navigation', { name: 'Hauptnavigation' }).getByRole('link', { name: 'Lieferaufträge' }).click()
  await expect(page.getByText('Testdaten-Vorschau · simulierte Aufträge')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Lieferaufträge', exact: true })).toBeVisible()
})
